#!/usr/bin/env node

import { mkdir, readFile, writeFile } from "node:fs/promises";
import { createRequire } from "node:module";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const require = createRequire(import.meta.url);
const loader = require(path.join(root, "math-map-content-loader.js"));
const admission = require(path.join(root, "math-content-admission.js"));
const adapter = require(path.join(root, "math-map-project-adapter.js"));
const graphContract = require(path.join(root, "graph-contract.js"));
const katex = require(path.join(root, "vendor/katex/katex.min.js"));
const manifestPath = path.join(root, "examples/generic-math-content/manifest.json");
const outputDirectory = path.join(root, "generated-math-content");
const checkOnly = process.argv.slice(2).includes("--check");

function projectPath(dataUrl) {
  if (typeof dataUrl !== "string" || !dataUrl.startsWith("/examples/generic-math-content/")) {
    throw new Error(`generic content dataUrl must stay under /examples/generic-math-content/: ${dataUrl}`);
  }
  return path.join(root, dataUrl.replace(/^\/+/, ""));
}

function dataAsset(_definition, data) {
  return `/* Generated by tools/build-generic-math-map-assets.mjs. Do not edit. */\n`
    + `window.CMATH_DATA = Object.freeze(${JSON.stringify(data, null, 2)});\n`;
}

function registryAsset(definitions) {
  return `/* Generated by tools/build-generic-math-map-assets.mjs. Do not edit. */\n`
    + `window.CMATH_GENERIC_MAP_REGISTRY = Object.freeze(${JSON.stringify({
      schema: "cmath-gamma.generic-math-map-runtime-registry/v0.1",
      maps: definitions,
    }, null, 2)});\n`;
}

async function expectedAssets() {
  const manifest = JSON.parse(await readFile(manifestPath, "utf8"));
  loader.validateManifest(manifest);
  const assets = new Map();
  const definitions = [];

  for (const definition of manifest.maps) {
    if (!/^[a-z0-9]+(?:-[a-z0-9]+)*$/u.test(definition.id)) {
      throw new Error(`map id is not safe for a generated filename: ${definition.id}`);
    }
    const data = JSON.parse(await readFile(projectPath(definition.dataUrl), "utf8"));
    const review = definition.reviewUrl
      ? JSON.parse(await readFile(projectPath(definition.reviewUrl), "utf8"))
      : null;
    const result = await loader.load(definition.id, {
      manifest,
      adapter,
      admission,
      parseMath: (math) => katex.renderToString(math, {
        throwOnError: true,
        trust: false,
        output: "mathml",
      }),
      fetchJson: async (url) => {
        if (url === definition.dataUrl) return data;
        if (url === definition.reviewUrl && review) return review;
        throw new Error(`unexpected data URL for ${definition.id}: ${url}`);
      },
    });
    const layout = result.model.layoutThrough(result.model.progressBatches.length);
    graphContract.assertLayout(layout);
    const fileName = `${definition.id}-project-data.js`;
    assets.set(fileName, dataAsset(definition, data));
    definitions.push({
      id: definition.id,
      title: definition.title ?? data.project.title,
      projectId: definition.projectId,
      workspaceViews: definition.workspaceViews,
      mathTextFormat: definition.mathTextFormat,
      contentAdmissionProfile: definition.contentAdmissionProfile,
      contentFingerprint: result.admission?.fingerprint ?? null,
      dataScript: `generated-math-content/${fileName}`,
      boundaryLabel: data.channelOptions.boundaryLabel ?? "一般数学内容 · Gamma-native 只读地图",
    });
  }

  assets.set("registry.js", registryAsset(definitions));
  return assets;
}

async function checkAssets(assets) {
  const stale = [];
  for (const [fileName, expected] of assets) {
    const target = path.join(outputDirectory, fileName);
    let actual = null;
    try {
      actual = await readFile(target, "utf8");
    } catch (error) {
      if (error.code !== "ENOENT") throw error;
    }
    if (actual !== expected) stale.push(path.relative(root, target));
  }
  if (stale.length) throw new Error(`generated generic map assets are stale: ${stale.join(", ")}`);
}

async function writeAssets(assets) {
  await mkdir(outputDirectory, { recursive: true });
  for (const [fileName, content] of assets) {
    await writeFile(path.join(outputDirectory, fileName), content, "utf8");
  }
}

const assets = await expectedAssets();
if (checkOnly) {
  await checkAssets(assets);
  process.stdout.write(`generic math map assets are current (${assets.size} files)\n`);
} else {
  await writeAssets(assets);
  process.stdout.write(`generated ${assets.size} generic math map assets\n`);
}

